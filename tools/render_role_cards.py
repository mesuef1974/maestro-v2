def _value_lines(key: str, value) -> list[str]:
    if isinstance(value, dict):
        return [f"- **{k}:** {v}" for k, v in value.items()]
    if isinstance(value, list):
        return ["، ".join(f"`{x}`" for x in value)] if key == "skills" else [f"- {x}" for x in value]
    return [str(value)]


def _merged_note(num: str, sid: str | None, aliases: dict | None) -> str:
    """الرقمُ المدمَج: اسمٌ مستعارٌ لهذه الجلسة، أم أُعيد استعمالُه لجلسةٍ حيّةٍ أخرى («_reused»، ترقيمُ 01 في 2026-10-21)."""
    reused = (aliases or {}).get("_reused") or {}
    if sid and num in reused and num not in (aliases or {}):
        return (f"والرقمُ {num} أُعيد استعمالُه لجلسةٍ حيّةٍ أخرى، فلا يُحال إلى هذه الجلسة إلا بطلبٍ صريح"
                " (`session_policy.aliases._reused` في tabs.json).")
    return f"والرقمُ {num} صار اسماً مستعاراً لهذه الجلسة (`session_policy.aliases` في tabs.json)."


def merged_sections(ch: dict, sid: str | None = None, aliases: dict | None = None) -> list[str]:
    """«## مدمَج من <الرقم · الاسم>» لكلّ ميثاقٍ في ch["merged"]: نصُّه الأصليّ كاملاً بلا حذف (المرحلة 2 من الدمج)."""
    out: list[str] = []
    for old, orig in (ch.get("merged") or {}).items():
        num = old.split(" · ")[0]
        out += [f"## مدمَج من {old}",
                f"> نصُّ الميثاق المدمَج كما كان قبل دمجه، بلا حذف؛ {_merged_note(num, sid, aliases)}", ""]

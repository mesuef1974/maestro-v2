def tab_of(title: str, tabs: dict) -> dict | None:
    """تبويبُ الجلسة: الذي يضمّها في members، وإلّا الذي يطابق أوّلَ خانتين من رقمها (TTSS)."""
    for t in tabs["tabs"]:
        if title in t.get("members", []):
            return t
    return {t.get("number"): t for t in tabs["tabs"]}.get(title.split(" · ")[0][:2])


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    project = sys.argv[1] if len(sys.argv) > 1 else "schoolos"
    tabs = json.loads((ROOT / "projects" / project / "tabs.json").read_text(encoding="utf-8"))
    aliases = tabs["session_policy"].get("aliases")
    global COMMON
    COMMON = COMMON + "\n" + common_tools(tabs) + COMMON_EXTRA
    outdir = ROOT / "role_cards"
    outdir.mkdir(exist_ok=True)
    rows = []
    details = outdir / "details"
    details.mkdir(exist_ok=True)
    (outdir / "COMMON.md").write_text(COMMON, encoding="utf-8")
    for title, ch in sorted(tabs["session_policy"]["charters"].items()):
        sid = title.split(" · ")[0]
        full = card(title, ch, tab_of(title, tabs), aliases)
        if sid in NUCLEUS_ROLES:
            (details / f"{sid}.md").write_text(full, encoding="utf-8")
            full = nucleus(title, ch, tab_of(title, tabs))
        (outdir / f"{sid}.md").write_text(full, encoding="utf-8")
        # index_line: سطرُ الخريطة إن كُتب في الميثاق (كان يُحرَّر يدويّاً في INDEX.md)، وإلّا أوّلُ 140 حرفاً من الدور
        line = ch.get("index_line") or ch["role"].split("؛")[0].split("。")[0][:140]
        if ch.get("merged"):
            line += " — مدمَجٌ فيها: " + "، ".join(ch["merged"])
        rows.append((title, line))
    for tab in tabs["tabs"]:
        if tab.get("id") == "execute":
            full = flexible_card(tab)
            if "04" in NUCLEUS_ROLES:
                (details / "04.md").write_text(full, encoding="utf-8")
                full = nucleus_flexible(tab)
            (outdir / "04.md").write_text(full, encoding="utf-8")
    (outdir / "INDEX.md").write_text(index(rows, aliases, tabs), encoding="utf-8")
    print(f"role_cards/ ✔ ({len(rows)} بطاقة + INDEX)")
    return 0


